import type { Network } from '@/shared/contracts/common'
import type { NftImageKey } from '@/shared/lib/nft-image'

import type { CategorySlug, CollectionSlug } from './catalog-taxonomy'
import type { EditionPreset, Stock } from './editions'

export interface NftRow {
  id: string
  name: string
  tokenId: string
  collection: CollectionSlug
  category: CategorySlug
  network: Network
  price: string
  previousPrice: string | null
  imageKey: NftImageKey
  rare: boolean
  trending: boolean
  listedHoursAgo: number
  editions: EditionPreset
  stock: Stock
  attributes: string[]
}

const row = (
  id: string,
  name: string,
  collection: CollectionSlug,
  category: CategorySlug,
  network: Network,
  price: string,
  imageKey: NftImageKey,
  listedHoursAgo: number,
  extra: Partial<
    Pick<NftRow, 'previousPrice' | 'rare' | 'trending' | 'editions' | 'stock' | 'attributes'>
  > = {},
): NftRow => ({
  id,
  name,
  tokenId: `#${name.split('#')[1]?.padStart(4, '0') ?? '0000'}`,
  collection,
  category,
  network,
  price,
  imageKey,
  listedHoursAgo,
  previousPrice: extra.previousPrice ?? null,
  rare: extra.rare ?? false,
  trending: extra.trending ?? false,
  editions: extra.editions ?? 'full',
  stock: extra.stock ?? 'normal',
  attributes: extra.attributes ?? ['Edição de colecionador'],
})

